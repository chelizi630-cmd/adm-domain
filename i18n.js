// 当前语言（默认从浏览器探测）
function detectInitialLang() {
    // 1. URL 参数 ?lang=xx（最高优先级，便于分享带语言链接）
    try {
        const url = new URLSearchParams(location.search);
        const urlLang = url.get('lang');
        if (urlLang && I18N[urlLang]) return urlLang;
    } catch (e) {}
    // 2. localStorage（用户主动选过的）
    const saved = localStorage.getItem('adm_lang');
    if (saved && I18N[saved]) return saved;
    // 3. 颛底中文（不根据浏览器语言自动切换，默认就是中文）
    return 'zh';
}

// 应用一套语言到 DOM
function applyLang(lang) {
    if (!I18N[lang]) lang = 'zh';
    const dict = I18N[lang];

    document.documentElement.lang = lang;

    // textContent
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = dict[key];
        if (val !== undefined) el.textContent = val;
    });
    // placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const val = dict[key];
        if (val !== undefined) el.placeholder = val;
    });
    // title (tooltip) / aria-label
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const val = dict[key];
        if (val !== undefined) el.title = val;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria');
        const val = dict[key];
        if (val !== undefined) el.setAttribute('aria-label', val);
    });

    // lang selector 高亮
    document.querySelectorAll('.lang-option').forEach(o => {
        o.classList.toggle('active', o.dataset.lang === lang);
    });

    localStorage.setItem('adm_lang', lang);
    window.ADM_LANG = lang;
}

// 暴露到全局
window.I18N = I18N;
window.applyLang = applyLang;
window.detectInitialLang = detectInitialLang;
